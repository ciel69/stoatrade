/** Проверка допуска (H1–H8). Не пройденная проверка, относящаяся только к живой торговле, вне режима «реальные деньги» это справка. */
export function humanGate(id: string, ok: boolean, msg: string, ctx: HumanCtx): Human | null {
  const def = GATES[id]
  if (!def) return null
  const live = ctx.mode === 'live'
  const raw = detailsOf(id, msg)
  if (ok) {
    const deferred = /проверится после|будет переключ/.test(msg)
    return make(deferred ? 'info' : 'ok', { title: deferred ? `${def.name}: проверится при запуске живой торговли` : def.ok, what: '', why: '', todo: deferred ? 'Действий не требуется.' : '' }, raw)
  }
  const p = def.fail(msg)
  const tone = def.tone(live, msg)
  const extra = id === 'H7' ? h7Parts(msg).slice(1) : []
  const title = extra.length ? `${p.title} (и ещё ${extra.length})` : p.title
  const what = extra.length ? `${p.what} Ещё: ${extra.map((e) => e.title.toLowerCase()).join('; ')}.` : p.what
  if (tone === 'info') return make('info', { title, what: def.liveOnly ? `${what}${PAPER_NOTE}` : what, why: p.why, todo: `${p.todo}${NO_NEED}` }, raw)
  return make(tone, { title, what, why: p.why, todo: p.todo }, raw)
}

