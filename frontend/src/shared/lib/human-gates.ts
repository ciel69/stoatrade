export const PRE_IDS = Object.keys(PRE)

/** Проверка перед запуском дня (P1–P16). sev: red — жёсткая, остальное — предупреждение. */
export function humanPre(id: string, ok: boolean, msg: string, sev: string | undefined): Human | null {
  const def = PRE[id]
  if (!def) return null
  const raw = detailsOf(id, msg)
  if (ok) return make('ok', { title: `${def.name}: в порядке`, what: '', why: '', todo: '' }, raw)
  const hard = sev === 'red' || sev === 'R'
  return make(hard ? 'bad' : 'warn', {
    title: def.fail,
    what: hard ? 'Пока это не исправлено, день запустить нельзя.' : 'Запуску это не мешает, но стоит знать.',
    why: 'Причина записана в подробностях для специалиста.',
    todo: def.todo,
  }, raw)
}
