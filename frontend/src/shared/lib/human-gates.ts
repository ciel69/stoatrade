/** Предупреждение (W1–W9). Для тех, что есть только справка перед запуском живой торговли, тревога не нужна. */
export function humanWarning(id: string, msg: string, ctx: HumanCtx): Human | null {
  const def = WARNS[id]
  if (!def) return null
  const tone = def.tone(ctx.mode === 'live')
  return make(tone, def.make(msg), detailsOf(id, msg))
}

