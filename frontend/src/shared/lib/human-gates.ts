/** Причины H7 по одной, в человеческом виде. */
export function h7Parts(msg: string): Part[] {
  const out: Part[] = []
  for (const piece of msg.split(';').map((s) => s.trim()).filter(Boolean)) {
    const hit = H7_PARTS.find(([re]) => re.test(piece))
    const part = hit ? hit[1] : H7_OTHER
    if (!out.some((p) => p.title === part.title)) out.push(part)
  }
  return out.length ? out : [H7_OTHER]
}

