/** Сообщение платформы над окном состояния (баннер). Известные формулировки объясняются, неизвестные получают запасной текст по уровню. */
export function humanBanner(text: string, level?: string | null): Human {
  const raw = detailsOf(text)
  for (const b of BANNERS) {
    const m = b.re.exec(text)
    if (m) {
      const r = b.build(m, level)
      return make(r.tone, r.part, raw)
    }
  }
  return humanText(text, level)
}
