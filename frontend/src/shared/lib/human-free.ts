      const day = dayLabel(m[1])
      if (!known.length) return { tone: 'info', part: { title: `День запущен (${day}), торговля идёт ${modeOn(m[2])}`, what: 'Все шаги запуска прошли без замечаний.', why: '', todo: 'Действий не требуется.' } }
