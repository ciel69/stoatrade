/** Свободная фраза сервера (предупреждение системы, причина закрытых входов). */
export function humanText(text: string, level?: string | null): Human {
  const raw = detailsOf(text)
  const hit = RULES.find((r) => r.re.test(text))
  const lv = toneOfLevel(level, 'info')
  if (hit) {
    const m = hit.re.exec(text) as RegExpExecArray
    return make(hit.tone ?? lv, hit.part(m), raw)
  }
  if (isPlain(text) && text.length <= 140) {
    // простой русский текст без служебных следов можно показать как есть
    return make(lv === 'ok' ? 'info' : lv, { title: cap(text.replace(/[.;\s]+$/, '')), what: '', why: '', todo: lv === 'bad' ? 'Если не проходит, покажите подробности разработчику.' : 'Действий не требуется.' }, raw)
  }
  return unknownHuman(lv === 'ok' ? 'info' : lv, raw)
}

