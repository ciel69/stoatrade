NODES.scanner = NODES.scan

export const NODE_IDS = Object.keys(NODES)

export const nodeLabel = (id: string, fallback?: string): string => NODES[id]?.label ?? (isPlain(fallback) ? fallback : 'Служба платформы')
/** Когда узел в красном, торговля остановлена. */
export const nodeStops = (id: string): boolean => NODES[id]?.stops ?? false

const SESSION_WORD: Record<string, string> = { day: 'торговый день', scalp: 'скальпинг', intraday: 'внутридневная', swing: 'свинг', position: 'позиционная' }
const ENV_WORD = /^(paper|testnet|live|observe)\b/

/** Текст узла для строки списка: короткая фраза без служебных слов и номеров процессов. */
export function nodeValue(n: HumanNodeInput & { at?: number | null; since?: number | null }, now: number): string {
  const text = n.text ?? ''
  const age = typeof n.at === 'number' ? `обновлено ${ageWord(now - n.at)}` : ''
  const up = typeof n.since === 'number' ? `работает ${duration(now - n.since)}` : ''
  const join = (...p: string[]): string => p.filter(Boolean).join(' · ')
  switch (n.id) {
    case 'exec': {
      if (/не запущен/.test(text)) return 'не запущен'
      const env = ENV_WORD.exec(text)?.[1]
      return join(env ? `работает ${modeOn(env)}` : 'работает', up)
    }
    case 'net':
      return n.level === 'ok' || n.level === 'info' ? 'биржа отвечает' : n.level === 'off' ? 'не используется' : ''
    case 'recon':
      return typeof n.at === 'number' ? `последняя сверка ${ageWord(now - n.at)}` : 'сверка не проводилась'
    case 'events': {
      const k = /wake: (\d+)/.exec(text)
      return join(k && Number(k[1]) > 0 ? `ждут обработки: ${k[1]}` : 'события доставляются', age)
    }
    case 'feed':
      return /остановлен/.test(text) ? 'остановлен' : join('цены поступают', age)
    case 'context':
      return /risk_off:/.test(text) ? 'рынок в режиме осторожности' : join('рынок спокоен', age)
    case 'session': {
      if (n.level === 'off') return 'не начата'
      const t = /^(\w+)\b/.exec(text)?.[1]
      const word = t ? SESSION_WORD[t] : undefined
      const to = /до (\d{1,2}:\d{2})/.exec(text)?.[1]
      return join(word ? `идёт ${word}` : 'идёт', to ? `до ${to}` : '')
    }
    case 'scan':
    case 'scanner':
      return join(n.level === 'off' ? 'не запущен' : 'работает', age)
    default:
      return join(n.level === 'ok' || n.level === 'info' ? 'в порядке' : n.level === 'off' ? 'не активно' : n.level === 'warn' ? 'работает с перебоями' : 'не работает', age)
  }
}

function ageWord(sec: number): string {
  const s = Math.max(0, Math.floor(sec))
  if (s < 5) return 'только что'
  if (s < 60) return `${s} с назад`
  if (s < 3600) return `${Math.floor(s / 60)} мин назад`
  if (s < 86400) return `${Math.floor(s / 3600)} ч назад`
  return `${Math.floor(s / 86400)} дн назад`
}

/** Объяснение состояния узла. Узел в норме: tone ok без текста. Неизвестный узел: запасной текст по уровню. */
export function humanNode(n: HumanNodeInput): Human {
  const raw = detailsOf(`узел ${n.id}`, n.text)
  if (n.level === 'ok' || n.level === 'info') return make('ok', { title: `${nodeLabel(n.id, n.label)}: в порядке`, what: '', why: '', todo: '' }, raw)
  const def = NODES[n.id]
  if (n.level === 'off') {
    const p = def?.off
    return p ? make('info', p, raw) : make('info', { title: `${nodeLabel(n.id, n.label)}: не активно`, what: 'Сейчас этот узел не используется.', why: 'Он включается вместе с торговым днём.', todo: 'Действий не требуется.' }, raw)
  }
  if (def) return make(n.level === 'bad' ? 'bad' : 'warn', n.level === 'bad' ? def.bad : def.warn, raw)
  const label = nodeLabel(n.id, n.label)
  return make(n.level === 'bad' ? 'bad' : 'warn', n.level === 'bad'
    ? { title: `${label}: не работает`, what: 'Это может мешать торговле.', why: 'Для этой службы пока нет понятного описания.', todo: 'Откройте «Подробности для специалиста» и перешлите их разработчику.' }
    : { title: `${label}: работает с перебоями`, what: 'Торговлю это не останавливает.', why: 'Для этой службы пока нет понятного описания.', todo: 'Действий не требуется. Если повторяется, покажите подробности разработчику.' }, raw)
}
