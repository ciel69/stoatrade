/** Код ответа платформы. Неизвестный код: запасной текст, сам код только в подробностях. */
export function humanCode(code: string, msg?: string): Human {
  const raw = detailsOf(code, msg)
  const def = CODES[code]
  if (!def) {
    return make('bad', {
      title: 'Платформа отклонила действие по причине, которую мы пока не умеем объяснить',
      what: 'Действие не выполнено.',
      why: 'Для этого ответа пока нет понятного описания.',
      todo: 'Откройте «Подробности для специалиста» и перешлите их разработчику.',
    }, raw)
  }
  return make(def.tone ?? (code === 'OK' ? 'ok' : 'bad'), def, raw)
}

/**
 * Текст отказа для окна или уведомления одной фразой: что случилось и что делать. Известный код объясняет словарь, неизвестный с простым русским текстом сервера показывает этот текст,
 * иначе запасная фраза. Код и исходный текст в такую строку не попадают (их берут в подробности через `humanCode(...).details`).
 */
export function failureText(code: string | null | undefined, msg?: string | null): string {
  if (code && code !== 'OK' && CODES[code]) {
    const c = CODES[code]
    return [c.title, c.todo].filter(Boolean).join('. ').replace(/\.\./g, '.').replace(/([^.])$/, '$1.')
  }
  const own = plainify(msg)
  if (own) return own
  return 'Платформа отклонила действие по причине, которую мы пока не умеем объяснить. Если повторяется, сообщите разработчику.'
}

