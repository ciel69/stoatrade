/** Почему реальные деньги недоступны в этом дашборде. link: нет связи с управлением; down: служба управления не отвечает; full: нет расширенного режима; off: выключатель владельца. */
export type LiveWhy = 'link' | 'down' | 'full' | 'off'

const WHY: Record<LiveWhy, string> = {
  link: 'Управление из этого дашборда недоступно, поэтому реальные деньги отсюда запустить нельзя.',
  down: 'Служба управления платформы не отвечает. Дождитесь, пока она вернётся, или запустите платформу.',
  full: 'Реальные деньги отсюда запускаются только в расширенном режиме управления. Включает его владелец в настройках дашборда.',
  off: 'Запуск на реальные деньги из этого дашборда выключен владельцем. Включить его может только владелец, в настройках платформы.',
}
export const liveWhyText = (why: LiveWhy): string => WHY[why]

/** Отказ платформы на проверку условий живого запуска: тексты про выключатель и расширенный режим. Остальные коды объясняет общий слой (failureText). */
export function liveRefusal(code: string | null | undefined): string | null {
  if (code === 'E_DISABLED') return WHY.off
  if (code === 'E_ELEVATE') return WHY.full
  return null
}

/** Пределы из фраз проверок платформы: «убыток за сутки 0.00 из 3.00 USDT» (H5) и «запусков за сутки 0 из 3» (H8). Нет такой фразы: нет и строки. */
export function liveLimitLines(gateMsgs: { H5?: string | null; H8?: string | null }): string[] {
  const out: string[] = []
  const loss = /убыток за сутки (-?\d+(?:\.\d+)?) из (\d+(?:\.\d+)?) USDT/.exec(gateMsgs.H5 ?? '')
  if (loss) out.push(`Дневной лимит убытка: ${loss[2]} USDT, сегодня уже ${loss[1]}.`)
  const runs = /запусков за сутки (\d+) из (\d+)/.exec(gateMsgs.H8 ?? '')
  if (runs) out.push(`Запусков на реальные деньги сегодня: ${runs[1]} из ${runs[2]}.`)
  return out
}
