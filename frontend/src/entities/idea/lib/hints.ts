export const NO_LEVEL_TEXT = 'Заметка без цены входа. Пока нет уровня и стопа, система за ней не следит и сделку по ней не откроет.'

export function ideaSideHint(side: IdeaItem['side']): TipContent {
  if (side === 'long') return { title: 'Лонг: ставка на рост', text: 'Идея выиграет, если цена вырастет, и проиграет, если упадёт.' }
  if (side === 'short') return { title: 'Шорт: ставка на падение', text: 'Идея выиграет, если цена упадёт, и проиграет, если вырастет.' }
  return { title: 'Направление не задано', text: 'У заметки нет стороны: неизвестно, на рост или на падение. Сделку по ней открыть нельзя.' }
}

/** Процент в шапке карточки: расстояние от текущей цены до уровня идеи. */
export function ideaDistHint(i: Pick<IdeaItem, 'dist_level_pct' | 'zone'>): TipContent {
  const d = i.dist_level_pct
  if (d == null) return { title: 'Цены нет', text: 'Свежей цены по монете пока нет, поэтому расстояние до уровня посчитать нельзя.' }
  if (i.zone) return { title: 'Цена у уровня', text: `Цена в пределах 0.3% от уровня идеи, до него ${fixed(Math.abs(d))}%. Мозг проверяет, стоит ли входить. Число зелёное, пока цена рядом с уровнем.` }
  const below = d <= 0
  return {
    title: `Цена на ${fixed(Math.abs(d))}% ${below ? 'ниже' : 'выше'} уровня`,
    text: `Это расстояние от текущей цены до уровня идеи. Чтобы идея сработала, цене нужно ${below ? 'вырасти' : 'снизиться'} на столько. Минус значит, что цена ниже уровня, без знака: выше. Чем меньше число, тем ближе вход.`,
  }
}

/** Срок справа в шапке карточки; left: секунд до конца срока, null: срока нет. */
export function ideaTtlHint(left: number | null): TipContent {
  if (left == null) return { title: 'Без срока', text: 'У идеи нет срока: она остаётся в списке, пока цена не дойдёт до уровня или идею не уберут.' }
  if (left <= 0) return { title: 'Срок вышел', text: 'Цена не дошла до уровня за отведённое время, идея скоро уйдёт во вкладку «Не сработали».' }
  return { title: `Осталось ${duration(left)}`, text: 'Идея истечёт, если цена не дойдёт до уровня за это время. Когда остаётся меньше получаса, срок подсвечивается жёлтым.' }
}

