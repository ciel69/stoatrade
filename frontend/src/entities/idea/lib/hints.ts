/** Падежные формы слов, после предлоги которых их нужно склонять: [именительный, родительный, дательный, творительный]. */
const LEVEL_FORMS: Record<string, readonly [string, string, string, string]> = {
  res: ['сопротивление', 'сопротивления', 'сопротивлению', 'сопротивлением'],
  sup: ['поддержка', 'поддержки', 'поддержке', 'поддержкой'],
  resistance: ['сопротивление', 'сопротивления', 'сопротивлению', 'сопротивлением'],
  support: ['поддержка', 'поддержки', 'поддержке', 'поддержкой'],
  pdh: ['вчерашний максимум', 'вчерашнего максимума', 'вчерашнему максимуму', 'вчерашним максимумом'],
  pdl: ['вчерашний минимум', 'вчерашнего минимума', 'вчерашнему минимуму', 'вчерашним минимумом'],
  dh: ['максимум дня', 'максимума дня', 'максимуму дня', 'максимумом дня'],
  dl: ['минимум дня', 'минимума дня', 'минимуму дня', 'минимумом дня'],
  wh: ['максимум недели', 'максимума недели', 'максимуму недели', 'максимумом недели'],
  wl: ['минимум недели', 'минимума недели', 'минимуму недели', 'минимумом недели'],
  s5m: ['экстремум 5м', 'экстремума 5м', 'экстремуму 5м', 'экстремумом 5м'],
  s1h: ['экстремум 1ч', 'экстремума 1ч', 'экстремуму 1ч', 'экстремумом 1ч'],
}
const PREP_CASE: Record<string, 1 | 2 | 3> = { до: 1, от: 1, у: 1, около: 1, из: 1, без: 1, для: 1, к: 2, над: 3, под: 3, за: 3, перед: 3, с: 3 }

/** Остальные сокращения, которые встречаются в заметках сканера и мозга. */
const TOKENS: Record<string, string> = {
  px: 'цена', price: 'цена', above: 'выше', below: 'ниже',
  tp: 'тейк', stop: 'стоп', sl: 'стоп', ttl: 'срок', entry: 'вход', risk: 'риск', reward: 'награда',
  long: 'лонг', short: 'шорт', bps: 'б.п.', range_5m: 'диапазон 5м',
  a5: 'размах свечи 5м', dpos: 'место в дне',
  ...Object.fromEntries(Object.entries(LEVEL_FORMS).map(([k, f]) => [k, f[0]])),
}

const NOT_WORD = String.raw`(?<![\p{L}\p{N}_.])`
const NOT_WORD_AFTER = String.raw`(?![\p{L}\p{N}_])`
const LEVEL_AFTER_PREP = new RegExp(String.raw`(?<![\p{L}\p{N}_])(${Object.keys(PREP_CASE).join('|')})(\s+)(${Object.keys(LEVEL_FORMS).join('|')})${NOT_WORD_AFTER}`, 'giu')
const TOKEN_RE = new RegExp(`${NOT_WORD}([A-Za-z][A-Za-z0-9_]*)${NOT_WORD_AFTER}`, 'gu')

/**
 * Заметка по-русски. Служебные сокращения сканера (res, sup, px, a5, pdh, above price) заменяются словами, остальной текст не трогается.
 * Если заметка не менялась, вернётся она же. Оригинал показывает IdeaDetail.
 */
export function noteRu(raw: string | null | undefined): string {
  const src = raw ?? ''
  if (!/[A-Za-z]/.test(src)) return src
  let t = src
  t = t.replace(LEVEL_AFTER_PREP, (_m, prep: string, sp: string, word: string) => `${prep}${sp}${LEVEL_FORMS[word.toLowerCase()][PREP_CASE[prep.toLowerCase()]]}`)
  t = t.replace(/(?<![\p{L}\p{N}_])above\s+price(?![\p{L}\p{N}_])/giu, 'выше цены').replace(/(?<![\p{L}\p{N}_])below\s+price(?![\p{L}\p{N}_])/giu, 'ниже цены')
  t = t.replace(TOKEN_RE, (m: string) => TOKENS[m] ?? TOKENS[m.toLowerCase()] ?? m)
  if (t !== src && /^[a-z]/.test(src)) t = t.charAt(0).toUpperCase() + t.slice(1)
  return t
}

/** Заметка изменилась при переводе (значит, оригинал стоит показать отдельно). */
export const noteTranslated = (raw: string | null | undefined): boolean => !!raw && noteRu(raw) !== raw

