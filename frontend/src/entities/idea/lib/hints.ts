/** Незнакомый тег показываем как есть, но без подчёркиваний и дефисов: «my_tag» → «my tag». */
export function humanizeTag(tag: string): string {
  return tag.replace(/[_-]+/g, ' ').replace(/\s{2,}/g, ' ').trim()
}

/** Подпись чипа сетапа по-русски; short: самая короткая форма для телефона. */
export function setupLabel(tag: string, form: 'full' | 'short' = 'full'): string {
  const s = SETUPS[tag]
  return s ? (form === 'short' ? s.short : s.name) : humanizeTag(tag)
}

/** Подсказка чипа сетапа; исходный код тега не теряется (строка «Код»). */
export function setupHint(tag: string): TipContent {
  const s = SETUPS[tag]
  const rows = [{ label: 'Код', value: tag }]
  if (s) return { title: s.title, text: s.text, rows }
  return { title: humanizeTag(tag), text: 'Метка, которую поставили идее. Подробного описания у неё нет.', rows }
}

