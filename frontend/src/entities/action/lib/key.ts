/**
 * Чистая логика ввода ключа провайдера (только запись). Формат тот же, что проверяет сервер (src/tb/dash2/ctlbridge.py, llmkey):
 * печатные символы ASCII без пробелов и переводов строк, не длиннее 512. Значение ключа здесь нигде не сохраняется и не попадает в тексты.
 */
export const KEY_MAX = 512

/** Края значения часто захватывают пробел или перевод строки при копировании: их убираем, внутри пробелы недопустимы. */
export const normalizeKey = (raw: string): string => raw.trim()

/** Почему значение не подходит (человеческим текстом) или null, если подходит. Пустое поле не ошибка ввода, а «ещё не введено»: возвращает null только для годного значения. */
export function keyProblem(raw: string): string | null {
  const v = normalizeKey(raw)
  if (!v) return 'Введите ключ.'
  if (v.length > KEY_MAX) return `Ключ длиннее ${KEY_MAX} символов: похоже, скопировано лишнее.`
  if (/\s/.test(v)) return 'В ключе не должно быть пробелов и переносов строк: скопируйте только сам ключ.'
  if (!/^[\x21-\x7e]+$/.test(v)) return 'Допустимы только латинские буквы, цифры и знаки: похоже, в ключе есть лишние символы.'
  return null
}

export interface KeyOutcome {
  ok: boolean
  /** код ответа сервера (OK, E_ARGS ...) или локальный: E_LINK нет связи, E_WAIT нет ответа, E_BUSY уже идёт отправка */
  code: string
  /** текст для человека; значение ключа в нём не встречается никогда */
  text: string
}

const TEXTS: Record<string, string> = {
  OK: 'Ключ сохранён.',
  E_ARGS: 'Ключ не принят: нужны печатные латинские символы без пробелов, не длиннее 512.',
  E_UNKNOWN: 'Провайдер неизвестен или ему не нужен ключ.',
  E_KEY: 'Ключ не принят сервером.',
  E_INTERNAL: 'Ключ не записан: ошибка на сервере. Попробуйте ещё раз.',
  E_AUTH: 'Ввод ключа недоступен в этом режиме входа.',
  E_ELEVATE: 'Ввод ключа выключен: владелец должен включить расширенное управление дашборда.',
  E_CSRF: 'Страница устарела: обновите её и повторите.',
  E_RATE: 'Слишком частые попытки: подождите минуту.',
  E_LINK: 'Нет связи с сервером: ключ не отправлен.',
  E_WAIT: 'Сервер не ответил за 15 секунд: неизвестно, сохранён ли ключ. Проверьте статус ключа.',
  E_BUSY: 'Предыдущий ключ ещё отправляется: дождитесь ответа.',
}

/** Текст по коду. Поле msg ответа сервера не используется вообще, чтобы в тексте не могло оказаться ничего лишнего. */
export function keyOutcomeText(code: string): string {
  if (TEXTS[code]) return TEXTS[code]
  return /^E_[A-Z_]{1,24}$/.test(code) ? 'Ключ не сохранён: платформа сообщила о причине, которую мы пока не умеем объяснить.' : 'Ключ не сохранён.'
}
