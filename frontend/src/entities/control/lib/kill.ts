/** Причина остановки одной фразой. Пустая причина не придумывается. */
export function reasonLine(reason: string | null | undefined): string {
  const r = (reason ?? '').trim().replace(/[.\s]+$/, '')
  return r ? `Причина: ${r}.` : 'Причина в журнале не указана.'
}

/**
 * Что с позициями. Остановка без закрытия оставляет позиции на месте под защитой стопов на бирже; остановка с закрытием закрывает их по рынку.
 * positions: сколько позиций открыто сейчас по данным исполнителя (null: неизвестно).
 */
export function positionsLine(flatten: boolean, positions: number | null | undefined): string {
  const n = positions == null ? null : Math.max(0, Math.round(positions))
  const word = (k: number) => `${k} ${plural(k, ['позиция', 'позиции', 'позиций'])}`
  if (flatten) {
    if (n === 0) return 'Позиции были закрыты по рынку: открытых сейчас нет.'
    if (n == null) return 'Была заказана остановка с закрытием позиций; сколько их осталось, сейчас неизвестно.'
    return `Остановка была с закрытием позиций, но ещё открыто: ${word(n)}. Пока они не закроются, снять остановку нельзя.`
  }
  if (n === 0) return 'Позиции не закрывались; открытых сейчас нет.'
  if (n == null) return 'Позиции не закрывались: они остаются на бирже под защитой своих стопов. Сколько их сейчас, неизвестно.'
  return `Позиции не закрывались: открыто ${word(n)}, их защищают стопы на бирже.`
}

/** Почему кнопки нет и что делать вместо неё (обе причины сводятся к команде в терминале). null: кнопка доступна. */
export function releaseNote(full: boolean, flagOn: boolean): string | null {
  if (!full) return 'Расширенное управление дашборда выключено, поэтому снять остановку здесь нельзя. Откройте терминал в папке проекта и выполните команду.'
  if (!flagOn) return 'Снятие остановки кнопкой выключено в настройках платформы: это решает владелец. Откройте терминал в папке проекта и выполните команду.'
  return null
}

/** Аварийная остановка снята и отражена в теме ctl. */
export function killCleared(ctl: CtlSnapshot | null | undefined): boolean {
  return !!ctl && !ctl.kill
}

export const RELEASE_TITLE = 'Снять аварийную остановку'

/** Что изменится, для окна подтверждения (строка под заголовком). */
export function releaseWhat(reason: string | null | undefined, live: boolean): string {
  const base = `${reasonLine(reason)} После снятия платформа останется остановленной, пока вы не запустите новый день.`
  return live ? `${base} Платформа работает на реальные деньги.` : base
}
